#!/usr/bin/env bun
/** voussoir - build tooling for Voussoir desktop apps.
 *
 *  Bun is development-time only. Nothing here ships to end users: `voussoir build`
 *  produces a Rust binary with no JS runtime inside.
 */

import { parseArgs, type Args } from "./args.ts";
import { fail } from "./proc.ts";
import { keygen, sign as signArtifact } from "./commands/keys.ts";
import { patch } from "./commands/patch.ts";
import { CLI_VERSION, update } from "./commands/update.ts";
import { init } from "./commands/init.ts";
import { dev } from "./commands/dev.ts";
import { build } from "./commands/build.ts";
import { doctor } from "./commands/doctor.ts";
import { docs } from "./commands/docs.ts";
import { runPackage } from "./commands/package.ts";
import * as android from "./commands/android.ts";
import * as ios from "./commands/ios.ts";

const HELP = `voussoir - minimal desktop apps with a Rust shell and a Bun toolchain

Usage
  voussoir <command> [options]

Commands
  init [dir]     scaffold a new app (default: current directory)
  dev            run the Bun dev server and launch the shell against it
  build          bundle the frontend and compile the release binary
  package        build, then wrap the binary in a platform installer
  android build  cross-compile and package an APK (or AAB with --aab)
  keygen         create the Ed25519 key that signs releases
  sign           print the sha256 and signature for a release artifact
  patch          build the delta between two release artifacts
  update         rebuild this CLI from its checkout (--check to only ask)
  android run    install and launch on a device or emulator
  ios build      cross-compile and build the simulator app (or --target device)
  ios run        install and launch on a booted iOS simulator
  ios verify     build, install, launch and assert the Rust entry is reached
  docs           validate docs/src, then build the website
  doctor         check the toolchain and report what is missing

Options
  --name <n>     init: app name (default: from directory)
  --force        init: write into a non-empty directory
  --port <n>     dev: dev server port (default 5177)
  --verbose      dev: record reloads, slow commands and refused navigations
  --debug        build: cargo debug profile instead of release
  --size         build: print the binary size
  --out <path>   build: copy the binary somewhere, creating its parent
  --wait         android run: keep streaming device logs until Ctrl-C
  --key <path>   sign: the Ed25519 private key (default voussoir-signing-key.pem)
  --out <path>   keygen: where to write the private key
  --from <ver>   patch: the version the patch upgrades from
  --feed <url>   update: read a prebuilt-binary feed instead of rebuilding
                   from the install.sh checkout (or VOUSSOIR_CLI_FEED)
  --check        update: report what is newer without changing anything
  --force        update: rebuild or install even when already current
  --icon <path>  package: application icon (256x256 PNG or .icns)
  --identifier   package: reverse-DNS id (default: derived from the app name)
  --package      init: Android package name (default: com.voussoir.<app>)
  --mobile       init: Android shell only, no desktop crate
  --abi          android build: arm64-v8a (default), x86_64, armeabi-v7a
  --release      android build: signed release APK instead of debug
  --aab          android build: signed Android App Bundle for Play upload
  --target       ios build: sim (default) or device (unsigned build)
  --json         doctor: machine-readable output
  --check        docs: validate SUMMARY.md and the links, build nothing
  -h, --help     show this help
  -V, --version  print the CLI version

Docs
  Frontend: src/ is bundled by Bun (TypeScript, JSX, CSS, HTML entries).
  Native:   native/src/main.rs registers commands; native/src/assets.rs is
            generated by the CLI and must not be edited by hand.
`;

const argv = Bun.argv.slice(2);
const args = parseArgs(argv);

// Read before parsing: `--version` starts with a dash, so the parser would turn
// it into the help command. A release build is checked with this before it is
// published, which is what makes a mis-built binary fail the release instead of
// reaching whoever updates into it.
if (argv.includes("--version") || argv.includes("-V")) {
  console.log(CLI_VERSION);
  process.exit(0);
}

if (args.help || args.command === "help") {
  console.log(HELP);
  process.exit(0);
}

let code = 0;

// Expected failures (no cargo, no NDK, a bad flag) throw, and this is the one
// place that turns them into the clean `voussoir:` line instead of a stack.
try {
switch (args.command) {
  case "init":
    code = init(args);
    break;
  case "dev":
    code = await dev(args);
    break;
  case "build":
    code = await build(args);
    break;
  case "doctor":
    code = await doctor(args);
    break;
  case "docs":
    code = await docs(args);
    break;
  case "package":
    code = await runPackage(args);
    break;
  case "keygen":
    code = keygen(args);
    break;
  case "sign":
    code = signArtifact(args);
    break;
  case "patch":
    code = patch(args);
    break;
  case "update":
    code = await update(args);
    break;
  case "android": {
    // `voussoir android <subcommand>`: the second positional names the action.
    const sub = args.positionals[0];
    const rest: Args = { ...args, command: sub ?? "help", positionals: args.positionals.slice(1) };
    switch (sub) {
      case "build":
        code = await android.build(rest);
        break;
      case "run":
        code = await android.runOnDevice(rest);
        break;
      default:
        console.error("voussoir android: expected `build` or `run`\n");
        console.log(HELP);
        code = 1;
    }
    break;
  }
  case "ios": {
    // `voussoir ios <subcommand>`: same shape as the android one.
    const sub = args.positionals[0];
    const rest: Args = { ...args, command: sub ?? "help", positionals: args.positionals.slice(1) };
    switch (sub) {
      case "build":
        code = await ios.build(rest);
        break;
      case "run":
        code = await ios.runOnDevice(rest);
        break;
      case "verify":
        code = await ios.verify(rest);
        break;
      default:
        console.error("voussoir ios: expected `build`, `run` or `verify`\n");
        console.log(HELP);
        code = 1;
    }
    break;
  }
  default:
    console.error(`voussoir: unknown command \`${args.command}\`\n`);
    console.log(HELP);
    code = 1;
  }
} catch (error) {
  fail(error instanceof Error ? error.message : String(error));
}

process.exit(code);
