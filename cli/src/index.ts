/**
 * Flags each command accepts.
 *
 * Without this, `voussoir build --relase` parses, the flag is dropped and the
 * build succeeds with the default profile: a typo silently produces the wrong
 * artifact. Rejecting an unknown flag is the only behaviour a user can notice.
 */
const FLAGS: Record<string, string[]> = {
  init: ["name", "package", "desktop", "mobile", "ios", "force"],
  dev: ["port", "verbose"],
  build: ["debug", "size", "out"],
  package: ["icon", "identifier", "debug"],
  doctor: ["json"],
  docs: ["check"],
  keygen: ["out"],
  sign: ["key"],
  patch: ["from", "key", "out"],
  update: ["check", "feed", "out", "force"],
  "android build": ["abi", "release", "aab", "api"],
  "android run": ["api", "wait"],
  "ios build": ["target"],
  "ios run": ["target", "no-build"],
  "ios verify": ["target", "no-build"],
};

/** `android` and `ios` are two-word commands; the rest are one. */
function commandKey(current: Args): string {
  if (current.command === "android" || current.command === "ios") {
    const sub = current.positionals[0];
    return sub === undefined ? current.command : `${current.command} ${sub}`;
  }
  return current.command;
}

/** Closest known flag, so a typo gets a correction rather than a list. */
function closestFlag(typed: string, known: string[]): string | undefined {
  const distance = (a: string, b: string): number => {
    const row = Array.from({ length: b.length + 1 }, (_, i) => i);
    for (let i = 1; i <= a.length; i++) {
      let previous = row[0]!;
      row[0] = i;
      for (let j = 1; j <= b.length; j++) {
        const held = row[j]!;
        row[j] = Math.min(
          row[j]! + 1,
          row[j - 1]! + 1,
          previous + (a[i - 1] === b[j - 1] ? 0 : 1),
        );
        previous = held;
      }
    }
    return row[b.length]!;
  };

  let best: string | undefined;
  let bestScore = 3;
  for (const candidate of known) {
    const score = distance(typed, candidate);
    if (score < bestScore) {
      best = candidate;
      bestScore = score;
    }
  }
  return best;
}

/** Throws on a flag the command does not read, which `fail` prints cleanly. */
function rejectUnknownFlags(current: Args, key: string): void {
  const known = FLAGS[key];
  if (known === undefined) return;
  const typed = Object.keys(current.flags);
  const unknown = typed.filter((flag) => !known.includes(flag));
  if (unknown.length === 0) return;

  const flag = unknown[0]!;
  const suggestion = closestFlag(flag, known);
  const hint = suggestion === undefined ? "" : `; did you mean \`--${suggestion}\`?`;
  throw new Error(
    `\`--${flag}\` is not an option of \`voussoir ${key}\`${hint} (accepts: ${
      known.map((name) => `--${name}`).join(", ")
    })`,
  );
}

const argv = Bun.argv.slice(2);
const args = parseArgs(argv);

// Read before parsing: `--version` starts with a dash, so the parser would turn
// it into the help command. A release build is checked with this before it is
// published, which is what makes a mis-built binary fail the release instead of
// reaching whoever updates into it.
if (argv.includes("--version") || argv.includes("-V")) {
  console.log(CLI_VERSION);
  process.exit(0);
}

if (args.help || args.command === "help") {
  console.log(COMMAND_HELP[commandKey(args)] ?? HELP);
  process.exit(0);
}

let code = 0;

// Expected failures (no cargo, no NDK, a bad flag) throw, and this is the one
// place that turns them into the clean `voussoir:` line instead of a stack.
try {
// Checked before dispatch so a typo never reaches a command that would silently
// ignore it and produce the wrong artifact.
rejectUnknownFlags(args, commandKey(args));

switch (args.command) {
  case "init":
    code = init(args);
    break;
  case "dev":
    code = await dev(args);
    break;
  case "build":
    code = await build(args);
    break;
  case "doctor":
    code = await doctor(args);
    break;
  case "docs":
    code = await docs(args);
    break;
  case "package":
    code = await runPackage(args);
    break;
  case "keygen":
    code = keygen(args);
    break;
  case "sign":
    code = signArtifact(args);
    break;
  case "patch":
    code = patch(args);
    break;
  case "update":
    code = await update(args);
    break;
  case "android": {
    // `voussoir android <subcommand>`: the second positional names the action.
    const sub = args.positionals[0];
    const rest: Args = { ...args, command: sub ?? "help", positionals: args.positionals.slice(1) };
    switch (sub) {
      case "build":
        code = await android.build(rest);
        break;
      case "run":
        code = await android.runOnDevice(rest);
        break;
      default:
        console.error("voussoir android: expected `build` or `run`\n");
        console.log(HELP);
        code = 1;
    }
    break;
  }
  case "ios": {
    // `voussoir ios <subcommand>`: same shape as the android one.
    const sub = args.positionals[0];
    const rest: Args = { ...args, command: sub ?? "help", positionals: args.positionals.slice(1) };
    switch (sub) {
      case "build":
        code = await ios.build(rest);
        break;
      case "run":
        code = await ios.runOnDevice(rest);
        break;
      case "verify":
        code = await ios.verify(rest);
        break;
      default:
        console.error("voussoir ios: expected `build`, `run` or `verify`\n");
        console.log(HELP);
        code = 1;
    }
    break;
  }
  default:
    console.error(`voussoir: unknown command \`${args.command}\`\n`);
    console.log(HELP);
    code = 1;
  }
} catch (error) {
  fail(error instanceof Error ? error.message : String(error));
}

process.exit(code);
